/* Version macros. Committed (not generated) so every build system compiles
 * the same header; the repository audit keeps the string equal to the root
 * VERSION file. */

#ifndef TEX_CORE_VERSION_H
#define TEX_CORE_VERSION_H

#define TEX_CORE_VERSION ((0 << 16) | (1 << 8) | 0)
#define TEX_CORE_VERSION_STRING "0.1.0"

#endif
